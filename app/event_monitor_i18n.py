def normalize_page_locale(locale: str | None) -> str:
    value = (locale or "").strip().lower()
    if value.startswith("zh"):
        return "zh-CN"
    return "en"


def normalize_report_language(language: str | None) -> str | None:
    value = (language or "").strip().lower()
    if not value:
        return None
    if value.startswith("zh"):
        return "zh-CN"
    if value.startswith("en"):
        return "en"
    return None


def resolve_report_language(language: str | None) -> str:
    return normalize_report_language(language) or DEFAULT_REPORT_LANGUAGE


def build_page_bundle(locale: str | None) -> dict[str, Any]:
    resolved = normalize_page_locale(locale)
    return {
        "locale": resolved,
        "reportLanguage": "en" if resolved == "en" else "zh-CN",
        "messages": MESSAGES[resolved],
    }
